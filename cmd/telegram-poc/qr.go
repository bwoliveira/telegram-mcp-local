func privateWrite(path string, b []byte) error {
	f, err := os.CreateTemp(filepath.Dir(path), ".poc-*")
	if err != nil {
		return err
	}
	name := f.Name()
	defer os.Remove(name)
	if err := f.Chmod(0600); err != nil {
		f.Close()
		return err
	}
	if _, err := f.Write(b); err != nil {
		f.Close()
		return err
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(name, path)
}
func loginQR(ctx context.Context, e *gotdengine.Engine, state, listen, env string) error {
	host, _, err := net.SplitHostPort(listen)
	if err != nil {
		return errors.New("invalid QR listener")
	}
	ip := net.ParseIP(host)
	if ip == nil || !ip.IsLoopback() {
		return errors.New("QR listener must be a literal loopback IP")
	}
	listener, err := net.Listen("tcp", listen)
	if err != nil {
		return err
	}
	defer listener.Close()
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return err
	}
	p := &qrPage{host: listener.Addr().String(), token: base64.RawURLEncoding.EncodeToString(b), state: engine.LoginStarting}
	server := &http.Server{Handler: p, ReadHeaderTimeout: 5 * time.Second, ReadTimeout: 10 * time.Second, WriteTimeout: 10 * time.Second, IdleTimeout: 30 * time.Second}
	serverErr := make(chan error, 1)
	go func() { serverErr <- server.Serve(listener) }()
	defer func() {
		c, cancel := context.WithTimeout(context.Background(), time.Second)
		defer cancel()
		_ = server.Shutdown(c)
		<-serverErr
	}()
	open := filepath.Join(state, "open.html")
	if err := privateWrite(open, []byte(`<!doctype html><meta name="referrer" content="no-referrer"><a href="http://`+p.host+`/#`+p.token+`">Open local Telegram login</a>`)); err != nil {
		return err
	}
	defer os.Remove(open)
	pngPath := filepath.Join(state, "qr.png")
	defer os.Remove(pngPath)
	fmt.Println("Open this private file in your browser:", open, "(do not share its contents).")
	if err := e.StartLogin(ctx, engine.LoginRequest{Method: engine.LoginQR}); err != nil {
		return err
	}
	tick := time.NewTicker(100 * time.Millisecond)
	defer tick.Stop()
	version := 0
	for {
		login := e.Login()
		p.mu.Lock()
		p.state = login.State
		p.mu.Unlock()
		if login.State == engine.LoginShowQR && login.QRVersion != version {
			png, err := qrcode.Encode(login.QRURL, qrcode.Medium, 320)
			if err != nil {
				return err
			}
			if err := privateWrite(pngPath, png); err != nil {
				return err
			}
			p.mu.Lock()
			p.png = png
			p.mu.Unlock()
			version = login.QRVersion
		}
		switch login.State {
		case engine.LoginWantPass:
			p.mu.Lock()
			p.png = nil
			p.mu.Unlock()
			_ = os.Remove(pngPath)
			if err := password(ctx, e, env); err != nil {
				return err
			}
		case engine.LoginDone:
			p.mu.Lock()
			p.state = engine.LoginDone
			p.png = nil
			p.mu.Unlock()
			_ = os.Remove(pngPath)
			fmt.Println("conectado")
			select {
			case <-ctx.Done():
				return ctx.Err()
			case <-time.After(3 * time.Second):
				return nil
			}
		case engine.LoginFailed:
			return errors.New(login.Error)
		case engine.LoginCancelled:
			return context.Canceled
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-tick.C:
		}
	}
}
