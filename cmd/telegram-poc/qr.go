type qrPage struct {
	mu          sync.Mutex
	host, token string
	png         []byte
	state       engine.LoginState
}

func (p *qrPage) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Cache-Control", "no-store")
	w.Header().Set("Referrer-Policy", "no-referrer")
	w.Header().Set("X-Content-Type-Options", "nosniff")
	w.Header().Set("Content-Security-Policy", "default-src 'self'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src 'self' blob:; connect-src 'self'; frame-ancestors 'none'")
	if r.Host != p.host || r.Method != "GET" {
		http.Error(w, "forbidden", http.StatusForbidden)
		return
	}
	// Static HTML contains no token, QR or account state. A file:// bootstrap
	// navigation is cross-site/Origin:null in Chromium; permit only this public
	// document, then enforce same-origin + bearer on all data endpoints.
	if r.URL.Path == "/" {
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		fmt.Fprint(w, qrHTML)
		return
	}
	if r.Header.Get("Origin") != "" && r.Header.Get("Origin") != "http://"+p.host {
		http.Error(w, "forbidden", http.StatusForbidden)
		return
	}
	site := r.Header.Get("Sec-Fetch-Site")
	if site != "" && site != "same-origin" && site != "none" {
		http.Error(w, "forbidden", http.StatusForbidden)
		return
	}
	got := strings.TrimPrefix(r.Header.Get("Authorization"), "Bearer ")
	if subtle.ConstantTimeCompare([]byte(got), []byte(p.token)) != 1 {
		http.Error(w, "unauthorized", 401)
		return
	}
	p.mu.Lock()
	defer p.mu.Unlock()
	switch r.URL.Path {
	case "/qr.png":
		if len(p.png) == 0 {
			http.Error(w, "QR not available", 404)
			return
		}
		w.Header().Set("Content-Type", "image/png")
		_, _ = w.Write(p.png)
	case "/status":
		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(map[string]any{"state": p.state, "connected": p.state == engine.LoginDone})
	default:
		http.NotFound(w, r)
	}
}

