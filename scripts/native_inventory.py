def check_asset(entry, source, transform, repo):
    path = repo / source
    if path.is_symlink() or not path.is_file():
        fail(f"project asset source missing: {source}")
    data = path.read_bytes()
    if transform == "exact":
        if sha256_bytes(data) != entry["sha256"]:
            fail(f"project asset {entry['path']} differs from {source}")
        return
    actual = Path(entry["absolute"]).read_bytes().decode("utf-8")
    expected = data.decode("utf-8")
    if transform == "appimage-desktop":
        stripped = "".join(line for line in actual.splitlines(True) if not line.startswith("X-AppImage-Version="))
        if stripped != expected:
            fail(f"project asset {entry['path']} is not {source} plus the linuxdeploy X-AppImage-Version key")
    elif transform == "deb-desktop":
        rewritten = re.sub(r"(?m)^Exec=.*$", "Exec=/opt/telegram-mcp/telegram-mcp", expected)
        if actual != rewritten:
            fail(f"project asset {entry['path']} is not {source} with the packaged Exec path")
    else:
        fail(f"unknown asset transform {transform}")


def find_tool(dpkg, tool, arch):
    for template in TOOLS[tool]:
        candidate = "/" + template.format(triplet=TRIPLETS[arch])
        real = real_host_path(dpkg, candidate)
        if real:
            return candidate, real
    fail(f"build tool {tool} not found on the build host")


def classify(root, profile_name, arch, go_hashes, host_root="/", repo=REPO, data_dir=DATA, embedded=True,
             patchelf=None):
    """Classify every payload entry; return the manifest model (without self entries' hashes)."""
    if profile_name not in PROFILES:
        fail(f"unknown native profile {profile_name}")
    if arch not in TRIPLETS:
        fail(f"unsupported native architecture {arch}")
    profile = PROFILES[profile_name]
    pins, legal_texts = load_pins(data_dir)
    reviews = load_reviews(data_dir) if profile["dpkg"] else {}
    patchelf_sha256 = None
    if profile_name == "linux-appimage":
        patchelf_sha256 = pins["inputs"]["linuxdeploy"]["architectures"][arch].get("patchelf_sha256")
        if not patchelf_sha256:
            fail(f"linuxdeploy pin for {arch} lacks the extracted patchelf SHA-256")
    root = Path(root)
    entries = scan(root)
    self_paths = set(EMBEDDED) if profile["embedded"] else set()
    if profile["embedded"] and embedded:
        missing = [p for p in self_paths if p not in entries]
        if missing:
            fail("embedded native inventory missing from payload: " + ", ".join(sorted(missing)))
    dpkg = Dpkg(host_root)
    packages, generators, used_inputs = {}, {}, set()
    files = []
    explicit = set(profile["go"]) | set(profile["assets"]) | set(profile["inventory"]) | set(profile["pinned"])
    explicit |= set(profile["generated"]) | self_paths
    if profile["dpkg"]:
        prefetch(dpkg, [p for p, e in entries.items() if e["type"] == "file" and p not in explicit], arch)
    if set(go_hashes) != profile["go"]:
        fail(f"{profile_name} Go payloads must be exactly {sorted(profile['go'])}, got {sorted(go_hashes)}")
    for relative in sorted(set(entries) | self_paths):
        if relative in self_paths:
            # The embedded manifest cannot hash itself; it is listed by path and
            # verified by regeneration from the final artifact instead.
            entry = entries.get(relative, {"path": relative, "type": "file"})
            if entry["type"] != "file" or "elf_machine" in entry:
                fail(f"embedded native inventory must be a regular non-ELF file: {relative}")
            files.append(({"path": relative, "type": "file", "class": "native-inventory"},
                          {"path": relative, "type": "file", "absolute": str(root / relative)}))
            continue
        entry = dict(entries[relative])
        entry["absolute"] = str(root / relative)
        record = {key: entry[key] for key in ("path", "type", "mode", "size", "sha256", "target") if key in entry}
        machine = entry.get("elf_machine")
        if machine is not None:
            if machine != ELF_MACHINES[arch]:
                fail(f"ELF {relative} is not built for {arch} (e_machine {machine})")
            record["elf"] = True
        if entry["type"] == "symlink":
            record["class"] = "symlink"
            record["resolves_to"] = resolve_symlink(root, relative, entries)
        elif relative in profile["go"]:
            if entry["sha256"] != go_hashes[relative]:
                fail(f"Go payload {relative} differs from the inventoried Go binary")
            if machine is None:
                fail(f"Go payload {relative} is not an ELF executable")
            record["class"] = "go-payload"
        elif relative in profile["assets"]:
            source, transform = profile["assets"][relative]
            if machine is not None:
                fail(f"untracked native executable posing as project asset: {relative}")
            check_asset(entry, source, transform, repo)
            record.update({"class": "project-asset", "source": source, "transform": transform})
        elif relative in profile["inventory"]:
            if machine is not None:
                fail(f"untracked native executable posing as inventory: {relative}")
            record["class"] = "generated-inventory"
        elif relative in profile["pinned"]:
            key = profile["pinned"][relative]
            expected = pins["inputs"][key]["architectures"][arch]["sha256"]
            if entry["sha256"] != expected:
                fail(f"{relative} does not match pinned input {key} ({expected})")
            used_inputs.add(key)
            record.update({"class": "pinned-input", "input": key})
        elif relative in profile["generated"]:
            rule = profile["generated"][relative]
            if machine is not None:
                fail(f"untracked native executable posing as generated file: {relative}")
            if "input" in rule:
                text = Path(entry["absolute"]).read_bytes().decode("utf-8", "replace")
                if not all(marker in text for marker in rule["markers"]):
                    fail(f"generated file {relative} lacks the markers of {rule['input']}")
                used_inputs.add(rule["input"])
                record.update({"class": "generated", "input": rule["input"]})
            else:
                tool = rule["tool"]
                if tool not in generators:
                    candidate, real = find_tool(dpkg, tool, arch)
                    owner = map_debian(dpkg, {"path": real.lstrip("/"), "sha256": sha256_file(dpkg.host(real))},
                                       arch, patchelf, patchelf_sha256)
                    generators[tool] = {"tool": tool, "path": real, "package": owner["package"]}
                record.update({"class": "generated", "tool": tool, "package": generators[tool]["package"]})
                packages.setdefault(generators[tool]["package"], set())
        elif profile["dpkg"]:
            origin = map_debian(dpkg, entry, arch, patchelf, patchelf_sha256)
            record.update({"class": "debian-package", **origin})
            packages.setdefault(origin["package"], set()).add(relative)
        else:
            fail(f"unmapped payload file in {profile_name}: {relative}")
        files.append((record, entry))
    # Every symlink must end at a covered regular file.
    covered = {record["path"] for record, _ in files if record["type"] == "file"}
    for record, _ in files:
        if record["type"] == "symlink" and record["resolves_to"] not in covered:
            fail(f"symlink {record['path']} resolves to an uncovered file")
    if profile_name == "linux-appimage":
        used_inputs.add("appimage-type2-runtime")
    package_records = load_packages(dpkg, packages, arch, reviews)
    return {"profile": profile_name, "arch": arch, "files": files, "packages": package_records,
            "generators": generators, "inputs": {k: pins["inputs"][k] for k in sorted(used_inputs)},
            "legal": legal_texts, "distribution": distribution(dpkg) if profile["dpkg"] else None}


def distribution(dpkg):
    path = dpkg.host("/etc/os-release")
    values = {}
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            if "=" in line:
                key, value = line.split("=", 1)
                values[key] = value.strip().strip('"')
    except OSError as error:
        fail(f"cannot read build host os-release: {error}")
    if values.get("ID") not in ("debian", "ubuntu"):
        fail(f"native Debian inventory requires a Debian or Ubuntu build root, not {values.get('ID')!r}")
    return {"id": values["ID"], "version_id": values.get("VERSION_ID", ""),
            "codename": values.get("VERSION_CODENAME", "")}


def load_common_licenses(dpkg, copyright_text, arch, package):
    """Load and verify every Debian common-license file referenced by copyright."""
    records = []
    paths = {match.rstrip(".,;:)") for match in COMMON_LICENSE.findall(copyright_text)}
    for path in sorted(paths):
        real = real_host_path(dpkg, path)
        if real is None or not real.startswith("/usr/share/common-licenses/"):
            fail(f"Debian package {package} references an unusable common license: {path}")
        owner = owner_of(dpkg, real, arch)
        if owner is None:
            fail(f"common license {path} referenced by {package} is not owned by a Debian package")
        expected = dpkg.md5sum(owner, arch, real)
        if expected is None or md5_file(dpkg.host(real)) != expected:
            fail(f"common license {path} referenced by {package} does not match {owner}'s md5sums")
        raw = dpkg.host(real).read_bytes()
        try:
            text = raw.decode("utf-8")
        except UnicodeError:
            fail(f"common license {path} referenced by {package} is not UTF-8")
        if not text.strip():
            fail(f"common license {path} referenced by {package} is empty")
        records.append({"path": path, "resolved_path": real, "sha256": sha256_bytes(raw),
                        "owner": owner, "text": text})
    return records


def load_packages(dpkg, packages, arch, reviews):
    if not packages:
        return []
    metadata = dpkg.metadata(sorted(packages))
    records, unreviewed = [], []
    for key in sorted(packages):
        meta = metadata[key]
        if meta["architecture"] not in (arch, "all"):
            fail(f"Debian package {key} has architecture {meta['architecture']}, not {arch}")
        doc = f"/usr/share/doc/{meta['name']}/copyright"
        real = real_host_path(dpkg, doc)
        if real is None or not real.startswith("/usr/share/doc/"):
            fail(f"Debian package {meta['binary']} has no usable {doc}")
        owner = owner_of(dpkg, real, arch)
        if owner is None:
            fail(f"copyright file {real} of {meta['binary']} is not owned by any package")
        expected = dpkg.md5sum(owner, arch, real)
        if expected is None or md5_file(dpkg.host(real)) != expected:
            fail(f"copyright file {real} of {meta['binary']} does not match {owner}'s md5sums")
        raw = dpkg.host(real).read_bytes()
        try:
            text = raw.decode("utf-8")
        except UnicodeError:
            fail(f"copyright file {real} of {meta['binary']} is not UTF-8")
        if not text.strip():
            fail(f"copyright file {real} of {meta['binary']} is empty")
        classification, findings, review = license_review(meta, text, reviews)
        common_licenses = load_common_licenses(dpkg, text, arch, meta["binary"])
        if classification == "review-required" and review is None:
            unreviewed.append((meta, sha256_bytes(raw), findings))
        records.append({**meta, "copyright_path": real, "copyright_sha256": sha256_bytes(raw),
                        "copyright_owner": owner, "copyright": text, "common_licenses": common_licenses,
                        "license_markers": classification,
                        "license_review": review, "files": sorted(packages[key])})
    if unreviewed:
        lines = []
        for meta, digest, findings in unreviewed:
            lines.append(f"{meta['name']} {meta['version']} (copyright sha256 {digest}):")
            lines.extend("    " + finding for finding in findings[:12])
            if len(findings) > 12:
                lines.append(f"    ... {len(findings) - 12} more")
        fail("forbidden GPL/AGPL legal markers need an explicit review decision in "
             "scripts/linux-native/license-review.json:\n" + "\n".join(lines))
    return records


