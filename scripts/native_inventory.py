def source_retrieval(dist, package):
    source, version = package["source"], package["source_version"]
    if dist["id"] == "ubuntu":
        url = f"https://launchpad.net/ubuntu/+source/{quote(source)}/{quote(version)}"
    else:
        url = f"https://snapshot.debian.org/package/{quote(source)}/{quote(version)}/"
    return f"apt-get source {source}={version}", url


def manifest_bytes(model):
    files = [record for record, _ in model["files"]]
    packages = []
    for package in model["packages"]:
        record = {key: package[key] for key in ("binary", "name", "architecture", "version", "source",
                                                "source_version", "copyright_path", "copyright_sha256",
                                                "license_markers", "license_review")}
        record["common_licenses"] = [
            {key: legal[key] for key in ("path", "resolved_path", "sha256", "owner")}
            for legal in package["common_licenses"]]
        packages.append(record)
    inputs = []
    for key, item in model["inputs"].items():
        arch_pin = item["architectures"][model["arch"]]
        inputs.append({"id": key, "name": item["name"], "version": item["version"], "url": arch_pin["url"],
                       "sha256": arch_pin["sha256"], "license": item["license"], "source": item["source"],
                       "static": [s["id"] for s in item.get("static", [])]})
    document = {"schema": SCHEMA, "profile": model["profile"], "architecture": model["arch"],
                "distribution": model["distribution"], "scope": SCOPE,
                "counts": {"files": len(files), "packages": len(packages), "inputs": len(inputs)},
                "files": files, "packages": packages, "inputs": inputs,
                "generators": [model["generators"][k] for k in sorted(model["generators"])]}
    return canonical(document)


