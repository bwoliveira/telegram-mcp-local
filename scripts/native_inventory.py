def payload_ref(record, sha256):
    return f"urn:telegram-mcp:payload:{quote(record['path'], safe='')}:{sha256}"


def deb_purl(dist, package):
    distro = dist["id"] if dist else "debian"
    qualifiers = f"arch={quote(package['architecture'])}"
    if dist and dist.get("version_id"):
        qualifiers += f"&distro={quote(distro + '-' + dist['version_id'])}"
    return f"pkg:deb/{distro}/{quote(package['name'])}@{quote(package['version'])}?{qualifiers}"


def input_ref(key, model, static=None):
    sha = model["inputs"][key]["architectures"][model["arch"]]["sha256"]
    return f"urn:telegram-mcp:pinned:{key}:{sha}" + (f":{static}" if static else "")


def sbom_parts(model, go_refs, runtime_sha256=None):
    """Return (components, dependency edges, direct refs) for the artifact SBOM."""
    components, edges, direct = [], {}, []
    package_refs = {}
    for package in model["packages"]:
        ref = deb_purl(model["distribution"], package)
        command, url = source_retrieval(model["distribution"], package)
        package_refs[package["binary"]] = ref
        package_refs[package["name"]] = ref
        components.append({
            "type": "library", "bom-ref": ref, "name": package["name"], "version": package["version"], "purl": ref,
            "properties": properties({
                "telegram-mcp:native:kind": "debian-package",
                "telegram-mcp:native:architecture": package["architecture"],
                "telegram-mcp:native:source-package": package["source"],
                "telegram-mcp:native:source-version": package["source_version"],
                "telegram-mcp:native:source-retrieval": f"{command} ; {url}",
                "telegram-mcp:native:copyright-path": package["copyright_path"],
                "telegram-mcp:native:copyright-sha256": package["copyright_sha256"],
                "telegram-mcp:native:gpl-markers": package["license_markers"],
                "telegram-mcp:native:license-review": package["license_review"]}),
            "licenses": ([{"license": {"name": f"Debian copyright file: {package['copyright_path']}",
                                       "text": {"contentType": "text/plain", "content": package["copyright"]}}}] +
                         [{"license": {"name": f"Debian common license: {legal['path']}",
                                       "text": {"contentType": "text/plain", "content": legal["text"]}}}
                          for legal in package["common_licenses"]])})
    for key, item in model["inputs"].items():
        arch_pin = item["architectures"][model["arch"]]
        ref = input_ref(key, model)
        values = {"telegram-mcp:native:kind": "pinned-input", "telegram-mcp:native:role": item["role"],
                  "telegram-mcp:native:url": arch_pin["url"], "telegram-mcp:native:source": item["source"],
                  "telegram-mcp:native:license": item["license"]}
        component = {"type": "application", "bom-ref": ref, "name": item["name"], "version": item["version"],
                     "hashes": [{"alg": "SHA-256", "content": arch_pin["sha256"]}],
                     "properties": properties(values),
                     "licenses": [{"license": {"name": f"Pinned legal text: {name}",
                                               "text": {"contentType": "text/plain", "content": model["legal"][name]}}}
                                  for name in item["legal"]]}
        components.append(component)
        if key == "appimage-type2-runtime":
            direct.append(ref)
            if runtime_sha256:
                values["telegram-mcp:native:artifact-prefix-sha256"] = runtime_sha256
                component["properties"] = properties(values)
            statics = []
            for static in item.get("static", []):
                static_ref = input_ref(key, model, static["id"])
                statics.append(static_ref)
                static_values = {"telegram-mcp:native:kind": "statically-linked",
                                 "telegram-mcp:native:license": static["license"],
                                 "telegram-mcp:native:source": static["source"],
                                 "telegram-mcp:native:source-sha256": static.get("source_sha256"),
                                 "telegram-mcp:native:modification": static.get("modification")}
                components.append({"type": "library", "bom-ref": static_ref, "name": static["name"],
                                   "version": static["version"], "properties": properties(static_values),
                                   "licenses": [{"license": {"name": f"Pinned legal text: {name}",
                                                             "text": {"contentType": "text/plain",
                                                                      "content": model["legal"][name]}}}
                                                for name in static["legal"]]})
            edges[ref] = sorted(statics)
    file_refs = {}
    for record, entry in model["files"]:
        if record["class"] == "native-inventory":
            sha = "embedded"
        elif entry["type"] == "file":
            sha = entry["sha256"]
        else:
            sha = sha256_bytes(entry["target"].encode("utf-8"))
        file_refs[record["path"]] = payload_ref(record, sha)
    for record, entry in model["files"]:
        ref = file_refs[record["path"]]
        values = {"telegram-mcp:native:kind": "payload-file", "telegram-mcp:native:path": record["path"],
                  "telegram-mcp:native:class": record["class"], "telegram-mcp:native:file-type": entry["type"],
                  "telegram-mcp:native:mode": entry.get("mode"), "telegram-mcp:native:symlink-target": entry.get("target"),
                  "telegram-mcp:native:owner": record.get("package") or record.get("input") or record.get("tool")
                  or record.get("source"), "telegram-mcp:native:origin": record.get("origin"),
                  "telegram-mcp:native:origin-sha256": record.get("origin_sha256"),
                  "telegram-mcp:native:transforms": ",".join(record.get("transforms", [])) or None,
                  "telegram-mcp:native:modified": ("true" if record.get("modified") else "false")
                  if record["class"] == "debian-package" else None}
        component = {"type": "file", "bom-ref": ref, "name": record["path"], "properties": properties(values)}
        if entry["type"] == "file" and "sha256" in entry:
            component["hashes"] = [{"alg": "SHA-256", "content": entry["sha256"]}]
        components.append(component)
        direct.append(ref)
        target = None
        if record["class"] == "go-payload":
            target = go_refs[record["path"]]
        elif record["class"] in ("debian-package",) or (record["class"] == "generated" and "tool" in record):
            target = package_refs[record["package"]]
        elif record["class"] in ("pinned-input", "generated"):
            target = input_ref(record["input"], model)
        elif record["class"] == "symlink":
            target = file_refs[record["resolves_to"]]
        if target:
            edges[ref] = [target]
    return components, edges, sorted(direct)


def embedded_outputs(model):
    return {MANIFEST_NAME: manifest_bytes(model), NOTICES_NAME: notices_bytes(model)}


def verify_embedded(root, model):
    """Embedded copies must equal what the final payload regenerates."""
    stale = []
    for name, content in embedded_outputs(model).items():
        path = Path(root) / EMBED_DIR / name
        if path.is_symlink() or not path.is_file() or path.read_bytes() != content:
            stale.append(f"{EMBED_DIR}/{name}")
    if stale:
        fail("embedded native inventory is missing or stale: " + ", ".join(stale))
