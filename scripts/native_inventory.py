def notices_bytes(model):
    chunks = [f"# Native payload notices: {model['profile']} ({model['arch']})\n\n", SCOPE, "\n\n"]
    if model["profile"] == "linux-appimage" or model["packages"]:
        chunks.append(offer_text(model))
    chunks.append("\n## Payload files\n\n")
    for record, _ in model["files"]:
        owner = (record.get("package") or record.get("input") or record.get("tool") or record.get("source")
                 or record.get("resolves_to") or "")
        digest = record.get("sha256", "(self)" if record["class"] == "native-inventory" else "symlink")
        chunks.append(f"- {record['path']} [{record['class']}{': ' + owner if owner else ''}] {digest}"
                      f"{' (modified at build)' if record.get('modified') else ''}\n")
    emitted_common = set()
    for package in model["packages"]:
        command, url = source_retrieval(model["distribution"], package)
        chunks.append(f"\n## Debian package {package['binary']} {package['version']}\n\n")
        chunks.append(f"Source package: {package['source']} {package['source_version']}\n")
        chunks.append(f"Source retrieval: {command} ; {url}\n")
        chunks.append(f"GPL/AGPL markers: {package['license_markers']}\n")
        if package["license_review"]:
            chunks.append(f"Review decision: {package['license_review']}\n")
        text = package["copyright"]
        chunks += [f"\n--- {package['copyright_path']} ---\n", text, "" if text.endswith("\n") else "\n"]
        for legal in package["common_licenses"]:
            if legal["path"] in emitted_common:
                continue
            emitted_common.add(legal["path"])
            chunks += [f"\n--- {legal['path']} (owner {legal['owner']}, sha256 {legal['sha256']}) ---\n",
                       legal["text"], "" if legal["text"].endswith("\n") else "\n"]
    for key, item in model["inputs"].items():
        arch_pin = item["architectures"][model["arch"]]
        chunks.append(f"\n## Pinned input {item['name']} ({item['version']})\n\n")
        chunks.append(f"Role: {item['role']}\nURL: {arch_pin['url']}\nSHA-256: {arch_pin['sha256']}\n"
                      f"License: {item['license']}\nSource: {item['source']}\n")
        legal = list(item["legal"])
        for static in item.get("static", []):
            chunks.append(f"Statically linked: {static['name']} {static['version']} ({static['license']}); "
                          f"source {static['source']}\n")
            legal += [name for name in static["legal"] if name not in legal]
        for name in legal:
            text = model["legal"][name]
            chunks += [f"\n--- {name} ---\n", text, "" if text.endswith("\n") else "\n"]
    return "".join(chunks).encode("utf-8")


def appimage_runtime(artifact, arch, pins):
    """Verify the runtime prefix of ARTIFACT against the pinned runtime; return its prefix SHA-256."""
    with open(artifact, "rb") as stream:
        header = stream.read(64)
        if len(header) != 64 or header[:6] != b"\x7fELF\x02\x01" or header[8:11] != b"AI\x02":
            fail("artifact is not an ELF64 type-2 AppImage")
        shoff = struct.unpack_from("<Q", header, 40)[0]
        shentsize, shnum, shstrndx = struct.unpack_from("<HHH", header, 58)
        size = shoff + shentsize * shnum
        if shentsize != 64 or not shnum or size > 64 * 1024 * 1024:
            fail("unsupported AppImage runtime section table")
        stream.seek(0)
        runtime = bytearray(stream.read(size))
        if stream.read(4) != b"hsqs":
            fail("SquashFS does not follow the AppImage runtime")
    sections = [struct.unpack_from("<IIQQQQIIQQ", runtime, shoff + i * 64) for i in range(shnum)]
    strings = sections[shstrndx][4]
    names = {}
    for section in sections:
        start = strings + section[0]
        names[bytes(runtime[start:runtime.index(b"\0", start)]).decode("ascii", "replace")] = section
    actual = sha256_bytes(runtime)
    for name in APPIMAGE_RUNTIME_SECTIONS:
        if name not in names:
            fail(f"AppImage runtime lacks section {name}")
        offset, length = names[name][4], names[name][5]
        runtime[offset:offset + length] = bytes(length)
    expected = pins["inputs"]["appimage-type2-runtime"]["architectures"][arch]["sha256"]
    if sha256_bytes(runtime) != expected:
        fail("AppImage runtime does not match the pinned type-2 runtime (outside appimagetool-written sections)")
    return actual


