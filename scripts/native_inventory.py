class NativeInventoryError(Exception):
    """The native payload cannot be inventoried safely."""


def fail(message) -> NoReturn:
    raise NativeInventoryError(message)


def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def sha256_file(path):
    result = hashlib.sha256()
    with open(path, "rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            result.update(block)
    return result.hexdigest()


def md5_file(path):
    result = hashlib.md5(usedforsecurity=False)
    with open(path, "rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            result.update(block)
    return result.hexdigest()


def canonical(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode("utf-8")


def properties(values):
    return [{"name": name, "value": str(value)} for name, value in sorted(values.items()) if value is not None]


# ---- pinned inputs and reviewed legal decisions -----------------------------

def load_pins(data_dir=DATA):
    try:
        pins = json.loads((data_dir / "pinned-inputs.json").read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        fail(f"cannot read pinned native inputs: {error}")
    if not isinstance(pins, dict) or pins.get("schema") != "telegram-mcp-native-pins/1":
        fail("pinned native inputs have an unknown schema")
    texts = {}
    for name, record in sorted(pins.get("legal", {}).items()):
        path = data_dir / "legal" / name
        if path.is_symlink() or not path.is_file():
            fail(f"pinned legal text missing: {name}")
        raw = path.read_bytes()
        if sha256_bytes(raw) != record.get("sha256"):
            fail(f"pinned legal text {name} does not match its recorded SHA-256")
        text = raw.decode("utf-8")
        if not text.strip():
            fail(f"pinned legal text {name} is empty")
        texts[name] = text
    for key, item in pins.get("inputs", {}).items():
        for legal in item.get("legal", []) + [x for s in item.get("static", []) for x in s.get("legal", [])]:
            if legal not in texts:
                fail(f"pinned input {key} references unknown legal text {legal}")
    return pins, texts


def load_reviews(data_dir=DATA):
    path = data_dir / "license-review.json"
    try:
        reviews = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        fail(f"cannot read native license review decisions: {error}")
    if not isinstance(reviews, dict) or reviews.get("schema") != "telegram-mcp-native-license-review/1":
        fail("native license review file has an unknown schema")
    return reviews.get("packages", {})


# ---- payload scan -----------------------------------------------------------

def scan(root):
    """Return {relative posix path: entry} for every regular file and symlink."""
    root = Path(root)
    if root.is_symlink() or not root.is_dir():
        fail(f"payload root is not a directory: {root}")
    entries = {}

    def onerror(error):
        raise error

    for directory, dirs, files in os.walk(root, followlinks=False, onerror=onerror):
        for name in sorted(dirs + files):
            path = Path(directory) / name
            relative = path.relative_to(root).as_posix()
            if any(ord(char) < 32 for char in relative):
                fail(f"payload path contains control characters: {relative!r}")
            info = os.lstat(path)
            if stat.S_ISDIR(info.st_mode):
                continue
            if stat.S_ISLNK(info.st_mode):
                entries[relative] = {"path": relative, "type": "symlink", "target": os.readlink(path)}
            elif stat.S_ISREG(info.st_mode):
                with open(path, "rb") as stream:
                    head = stream.read(20)
                entry = {"path": relative, "type": "file", "mode": f"{stat.S_IMODE(info.st_mode):04o}",
                         "size": info.st_size, "sha256": sha256_file(path)}
                if head[:4] == b"\x7fELF":
                    if len(head) < 20 or head[4] != 2 or head[5] != 1:
                        fail(f"unsupported ELF class/byte order: {relative}")
                    entry["elf_machine"] = struct.unpack_from("<H", head, 18)[0]
                entries[relative] = entry
            else:
                fail(f"unsupported file type in payload: {relative}")
    return entries


def resolve_symlink(root, relative, entries, absolute_root=True):
    """Resolve a payload symlink inside the payload; absolute targets are payload-rooted."""
    seen = set()
    current = relative
    while True:
        entry = entries.get(current)
        if entry is None:
            fail(f"symlink {relative} resolves to a missing payload file: {current}")
        if entry["type"] == "file":
            return current
        if current in seen or len(seen) > 40:
            fail(f"symlink loop in payload: {relative}")
        seen.add(current)
        target = entry["target"]
        if target.startswith("/"):
            if not absolute_root:
                fail(f"absolute symlink in payload: {relative} -> {target}")
            joined = PurePosixPath(target.lstrip("/"))
        else:
            joined = PurePosixPath(current).parent / target
        parts = []
        for part in joined.parts:
            if part in ("", "."):
                continue
            if part == "..":
                if not parts:
                    fail(f"symlink escapes the payload: {relative} -> {target}")
                parts.pop()
            else:
                parts.append(part)
        if not parts:
            fail(f"symlink resolves to the payload root: {relative}")
        current = "/".join(parts)
        # Directories along the way may themselves be symlinks; resolve prefix links.
        for index in range(1, len(parts)):
            prefix = "/".join(parts[:index])
            if prefix in entries and entries[prefix]["type"] == "symlink":
                resolved_prefix = resolve_symlink(root, prefix, entries, absolute_root)
                current = "/".join([resolved_prefix] + parts[index:])
                break
        if (Path(root) / current).is_dir() and not (Path(root) / current).is_symlink():
            fail(f"symlink resolves to a directory: {relative}")


# ---- Debian package ownership ------------------------------------------------

class Dpkg:
    """dpkg-query/md5sums access against an installed root (default '/')."""

    def __init__(self, host_root="/"):
        self.host_root = Path(host_root)
        self.owner_cache = {}

    def host(self, absolute):
        return self.host_root / absolute.lstrip("/")

    def query(self, *args):
        command = ["dpkg-query"]
        if self.host_root != Path("/"):
            command.append(f"--admindir={self.host('/var/lib/dpkg')}")
        try:
            return subprocess.run([*command, *args], capture_output=True, text=True, encoding="utf-8")
        except OSError as error:
            fail(f"cannot run dpkg-query: {error}")

    def owners(self, paths):
        """Map literal absolute paths to owning package lists via dpkg-query -S."""
        pending = sorted({p for p in paths if p not in self.owner_cache})
        for path in pending:
            if not path.startswith("/") or any(char in path for char in "*[?\\"):
                fail(f"refusing non-literal dpkg ownership query: {path!r}")
        for start in range(0, len(pending), 200):
            chunk = pending[start:start + 200]
            result = self.query("-S", "--", *chunk)
            found = {}
            for line in result.stdout.splitlines():
                if line.startswith("diversion by "):
                    target = line.split(": ", 1)[-1]
                    found.setdefault(target, []).append("<diverted>")
                    continue
                if ": " not in line:
                    continue
                packages, path = line.split(": ", 1)
                found.setdefault(path, []).extend(p.strip() for p in packages.split(","))
            for path in chunk:
                self.owner_cache[path] = sorted(set(found.get(path, [])))
        return {path: self.owner_cache[path] for path in paths}

    def metadata(self, packages):
        fmt = ("${binary:Package}\\t${Package}\\t${Architecture}\\t${Version}\\t"
               "${source:Package}\\t${source:Version}\\t${db:Status-Abbrev}\\n")
        result = self.query("-W", "-f", fmt.encode().decode("unicode_escape"), "--", *sorted(packages))
        if result.returncode:
            fail(f"dpkg-query -W failed: {result.stderr.strip()}")
        records = {}
        for line in result.stdout.splitlines():
            fields = line.split("\t")
            if len(fields) != 7:
                fail(f"unexpected dpkg-query metadata line: {line!r}")
            binary, name, arch, version, source, source_version, status = fields
            if status.strip() != "ii":
                fail(f"Debian package {binary} is not fully installed (status {status.strip()!r})")
            if not all((binary, name, arch, version, source, source_version)):
                fail(f"incomplete Debian metadata for {binary or name}")
            record = {"binary": binary, "name": name, "architecture": arch, "version": version,
                      "source": source, "source_version": source_version}
            for key in {binary, name, f"{name}:{arch}"}:
                records[key] = record
        missing = [p for p in packages if p not in records]
        if missing:
            fail(f"dpkg-query returned no metadata for: {', '.join(sorted(missing))}")
        return records

    def md5sum(self, package, arch, absolute):
        info = self.host("/var/lib/dpkg/info")
        name = package.split(":", 1)[0]
        wanted = {absolute.lstrip("/")}
        wanted.update(alt.lstrip("/") for alt in usrmerge_alternates(absolute))
        for candidate in (f"{name}:{arch}.md5sums", f"{name}.md5sums"):
            path = info / candidate
            if not path.is_file():
                continue
            for line in path.read_text(encoding="utf-8", errors="surrogateescape").splitlines():
                parts = line.split(None, 1)
                if len(parts) == 2 and parts[1] in wanted:
                    return parts[0]
        return None


def usrmerge_alternates(absolute):
    result = []
    for merged in ("/lib", "/lib64", "/bin", "/sbin"):
        if absolute.startswith(merged + "/"):
            result.append("/usr" + absolute)
        if absolute.startswith("/usr" + merged + "/"):
            result.append(absolute[len("/usr"):])
    return result


def host_candidates(relative, arch):
    triplet = TRIPLETS[arch]
    candidates = ["/" + relative]
    if relative.startswith("usr/lib/"):
        suffix = relative[len("usr/lib/"):]
        candidates += [f"/usr/lib/{triplet}/{suffix}", f"/lib/{triplet}/{suffix}", f"/usr/lib/{suffix}",
                       f"/lib/{suffix}", f"/usr/lib64/{suffix}", f"/lib64/{suffix}"]
    seen, unique = set(), []
    for candidate in candidates:
        if candidate not in seen:
            seen.add(candidate)
            unique.append(candidate)
    return unique


def real_host_path(dpkg, absolute):
    host = dpkg.host(absolute)
    if not os.path.lexists(host):
        return None
    real = Path(os.path.realpath(host))
    try:
        relative = real.relative_to(Path(os.path.realpath(dpkg.host_root)))
    except ValueError:
        fail(f"host path escapes the package root: {absolute}")
    if not real.is_file():
        return None
    return "/" + relative.as_posix()


def owner_of(dpkg, absolute, arch):
    """Return the single package owning absolute (trying usr-merge aliases)."""
    queries = [absolute] + usrmerge_alternates(absolute)
    owners = dpkg.owners(queries)
    packages = sorted({p for q in queries for p in owners[q]})
    if "<diverted>" in packages:
        fail(f"{absolute} is diverted; its package origin is ambiguous")
    packages = [p for p in packages if ":" not in p or p.split(":", 1)[1] == arch]
    if len(packages) != 1:
        return None if not packages else fail(f"{absolute} is owned by several packages: {', '.join(packages)}")
    return packages[0]


def host_origins(dpkg, relative, arch):
    origins = {}
    for candidate in host_candidates(relative, arch):
        real = real_host_path(dpkg, candidate)
        if real:
            origins.setdefault(real, []).append(candidate)
    return origins


def prefetch(dpkg, relatives, arch):
    """Batch every dpkg-query -S lookup the later per-file mapping needs."""
    queries = set()
    for relative in relatives:
        for real, aliases in host_origins(dpkg, relative, arch).items():
            for path in [real, *aliases]:
                queries.add(path)
                queries.update(usrmerge_alternates(path))
    dpkg.owners(sorted(queries))


def reproduce_linuxdeploy_transform(dpkg, origin, entry, arch, patchelf, expected_patchelf_sha256):
    """Reproduce the only byte transformations allowed for Debian payload files.

    linuxdeploy runs its pinned patchelf with an $ORIGIN RUNPATH. The build then
    performs one fixed-length WebKitGTK helper-path rewrite. Attribution is
    accepted only when applying those exact operations to package bytes produces
    the exact payload bytes.
    """
    relative = entry["path"]
    if entry.get("elf_machine") != ELF_MACHINES[arch]:
        return None
    if not patchelf:
        return None
    tool = Path(patchelf)
    if tool.is_symlink() or not tool.is_file():
        fail(f"pinned linuxdeploy patchelf is not a regular file: {tool}")
    actual_tool_sha = sha256_file(tool)
    if not expected_patchelf_sha256 or actual_tool_sha != expected_patchelf_sha256:
        fail(f"linuxdeploy patchelf does not match its pinned SHA-256 ({expected_patchelf_sha256})")
    with tempfile.TemporaryDirectory(prefix="telegram-mcp-patchelf-") as directory:
        candidate = Path(directory) / "payload"
        shutil.copyfile(dpkg.host(origin), candidate)
        result = subprocess.run([str(tool), "--set-rpath", "$ORIGIN", str(candidate)],
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=False)
        if result.returncode:
            fail(f"pinned patchelf could not reproduce linuxdeploy's RUNPATH transform for {relative}: "
                 f"{result.stderr.strip()}")
        transforms = ["linuxdeploy-patchelf-set-rpath-$ORIGIN"]
        if Path(relative).name.startswith("libwebkit2gtk-4.1.so"):
            data = candidate.read_bytes()
            rewritten = data.replace(b"/usr/lib/", b"././/lib/")
            if rewritten != data:
                candidate.write_bytes(rewritten)
                transforms.append("webkitgtk-helper-path-/usr/lib/-to-././/lib/")
        if sha256_file(candidate) == entry["sha256"]:
            return transforms
    return None


def map_debian(dpkg, entry, arch, patchelf=None, expected_patchelf_sha256=None):
    relative = entry["path"]
    origins = host_origins(dpkg, relative, arch)
    if not origins:
        fail(f"unmapped payload file (no host origin under the Debian library paths): {relative}")
    if len(origins) > 1:
        # Prefer an unmodified byte-identical origin; otherwise the single
        # package-owned candidate. Anything else is ambiguous.
        matching = [real for real in origins if sha256_file(dpkg.host(real)) == entry["sha256"]]
        if len(matching) != 1:
            matching = [real for real in origins if owner_of(dpkg, real, arch)]
        if len(matching) != 1:
            fail(f"ambiguous host origin for {relative}: {', '.join(sorted(origins))}")
        origins = {matching[0]: origins[matching[0]]}
    (real, aliases), = origins.items()
    package = owner_of(dpkg, real, arch)
    if package is None:
        for alias in aliases:
            package = owner_of(dpkg, alias, arch)
            if package:
                break
    if package is None:
        fail(f"unmapped payload file (no Debian package owns {real}): {relative}")
    # Host aliases are symlinks (e.g. a -dev package's libfoo.so); the bytes come
    # from the resolved file, whose package md5sums entry must match below.
    expected = dpkg.md5sum(package, arch, real)
    if expected is None:
        fail(f"cannot verify installed bytes of {real}: no md5sums entry in {package}")
    if md5_file(dpkg.host(real)) != expected:
        fail(f"installed {real} does not match {package}'s md5sums; refusing an unverifiable origin")
    origin_sha = sha256_file(dpkg.host(real))
    transforms = []
    if origin_sha != entry["sha256"]:
        transforms = reproduce_linuxdeploy_transform(
            dpkg, real, entry, arch, patchelf, expected_patchelf_sha256)
        if transforms is None:
            fail(f"payload {relative} does not match the trusted Debian bytes or an allowed build transformation")
    return {"package": package, "origin": real, "origin_sha256": origin_sha,
            "modified": bool(transforms), "transforms": transforms}


# ---- GPL/AGPL legal markers ------------------------------------------------

def dep5_paragraphs(text):
    paragraph, result = [], []
    for line in text.splitlines() + [""]:
        if line.strip():
            paragraph.append(line)
        elif paragraph:
            result.append(paragraph)
            paragraph = []
    parsed = []
    for lines in result:
        fields, key = {}, None
        for line in lines:
            if line[:1] in (" ", "\t") and key:
                fields[key].append(line.strip())
            elif ":" in line:
                key, value = line.split(":", 1)
                key = key.strip().lower()
                fields[key] = [value.strip()]
            else:
                key = None
        parsed.append(fields)
    return parsed


def license_permitted(expression):
    """True when the DEP-5 expression can be satisfied without any GPL/AGPL licence."""
    tokens = re.findall(r"\(|\)|,|[^\s(),]+", expression)

    def parse_or(index):
        value, index = parse_and(index)
        while index < len(tokens) and tokens[index].lower() == "or":
            other, index = parse_and(index + 1)
            value = value or other
        return value, index

    def parse_and(index):
        value, index = parse_atom(index)
        while index < len(tokens) and tokens[index] in (",", "and", "AND", "And"):
            if tokens[index] == "," and index + 1 < len(tokens) and tokens[index + 1].lower() in ("and", "or"):
                index += 1
                if tokens[index].lower() == "or":
                    break
            other, index = parse_atom(index + 1)
            value = value and other
        return value, index

    def parse_atom(index):
        if index >= len(tokens):
            raise ValueError("truncated licence expression")
        if tokens[index] == "(":
            value, index = parse_or(index + 1)
            if index >= len(tokens) or tokens[index] != ")":
                raise ValueError("unbalanced licence expression")
            return value, index + 1
        name, index = tokens[index], index + 1
        if index < len(tokens) and tokens[index].lower() == "with":
            index += 1
            while index < len(tokens) and tokens[index].lower() not in ("and", "or", ")", ","):
                index += 1
        return not GPL_NAME.match(name), index

    try:
        value, index = parse_or(0)
        if index != len(tokens):
            raise ValueError("trailing licence tokens")
        return value
    except ValueError:
        return not GPL_WORD.search(expression)


def build_only(globs):
    return bool(globs) and all(BUILD_ONLY_DIRS.search(glob.lstrip("./")) or BUILD_ONLY_FILES.search(glob)
                               for glob in globs)


def classify_copyright(text):
    """Return (classification, findings) for a Debian copyright file.

    no-gpl-marker: no GPL/AGPL token or phrase at all (LGPL is not a marker).
    gpl-build-or-test-files-only: machine-readable DEP-5 whose GPL/AGPL-only
        paragraphs cover only build machinery, tests, docs or debian/*.
    gpl-only-as-alternative-or-definition: GPL appears only as one option of a
        disjunction or in standalone licence-text paragraphs.
    review-required: anything else (needs a hash-pinned review decision).
    """
    if not GPL_TOKEN.search(text) and not GPL_PHRASE.search(text):
        return "no-gpl-marker", []
    paragraphs = dep5_paragraphs(text)
    machine_readable = bool(paragraphs) and "format" in paragraphs[0] and "copyright-format" in " ".join(paragraphs[0]["format"])
    if not machine_readable:
        findings = [f"line {number}: {line.strip()[:160]}" for number, line in enumerate(text.splitlines(), 1)
                    if GPL_TOKEN.search(line) or GPL_PHRASE.search(line)]
        return "review-required", findings
    findings, build = [], False
    for fields in paragraphs:
        if "license" not in fields or ("files" not in fields and "format" not in fields):
            continue
        expression = fields["license"][0]
        if not expression:
            continue
        if not license_permitted(expression):
            globs = " ".join(fields.get("files", [])).split()
            if build_only(globs):
                build = True
                continue
            files = " ".join(globs) if globs else "(header)"
            findings.append(f"Files: {files[:200]} | License: {expression}")
    if findings:
        return "review-required", findings
    return ("gpl-build-or-test-files-only" if build else "gpl-only-as-alternative-or-definition"), []


def license_review(package, text, reviews):
    classification, findings = classify_copyright(text)
    review = None
    if classification == "review-required":
        digest = sha256_bytes(text.encode("utf-8"))
        records = reviews.get(package["name"], [])
        matches = [record for record in records if isinstance(record, dict)
                   and record.get("copyright_sha256") == digest
                   and str(record.get("reason", "")).strip()] if isinstance(records, list) else []
        if len(matches) != 1:
            return classification, findings, None
        if matches[0].get("decision") != "allowed":
            fail(f"Debian package {package['name']} {package['version']} is forbidden by its license review: "
                 f"{matches[0]['reason'].strip()}")
        review = matches[0]["reason"].strip()
    return classification, findings, review


